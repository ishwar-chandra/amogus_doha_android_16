#!/usr/bin/env bash
# =============================================================================
# crdroid-16/refresh-manifest.sh - (re)generate crdroid-16/default.xml
#
# Builds ONE self-contained repo manifest for "crDroid on Android 16" from:
#   * crdroidandroid/android  branch 16.0  (default.xml + the two snippets)
#   * the 27 doha device-side projects, copied VERBATIM (same pinned SHAs)
#     from this repo's root default.xml - the pins of the working
#     LineageOS 23.2 build
#
# What it changes versus crDroid's own manifest (and why):
#   1. <include>s are inlined       -> repo init -m crdroid-16/default.xml
#                                      then needs no extra files
#   2. remote "github" fetch=".."   -> https://github.com/ (a relative remote
#                                      resolves against the manifest repo URL,
#                                      which here is a local path)
#   3. unused ssh-only remote "private" is dropped
#   4. the 4 community remotes the doha projects use are added
#   5. any crDroid/AOSP project sitting at the same path as a doha project
#      is <remove-project>ed first (today: platform/external/fastrpc)
#
# crDroid's branch moves daily; the result is NOT SHA-pinned (same as
# crdroid-17/). After every sync build.sh records the exact commit of every
# project in <src>/.repo/doha-crdroid16-pins.xml (see crdroid-16/README.md).
#
# Usage:  bash crdroid-16/refresh-manifest.sh          (needs curl, git, python3)
#         CRDROID_BRANCH=16.0-qpr1 bash crdroid-16/refresh-manifest.sh
# =============================================================================
set -euo pipefail
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
BRANCH=${CRDROID_BRANCH:-16.0}
BASE=https://raw.githubusercontent.com/crdroidandroid/android/$BRANCH
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
mkdir -p "$tmp/snippets"
for f in default.xml snippets/crdroid.xml snippets/lineage.xml; do
  curl -fsSL --retry 3 -m 120 "$BASE/$f" -o "$tmp/$f" || { echo "refresh-manifest: cannot fetch $BASE/$f" >&2; exit 1; }
done
head_sha=$(git ls-remote https://github.com/crdroidandroid/android "refs/heads/$BRANCH" | cut -f1)
[ -n "$head_sha" ] || { echo "refresh-manifest: branch $BRANCH not found" >&2; exit 1; }

python3 - "$tmp" "$ROOT" "$HERE/default.xml" "$BRANCH" "$head_sha" <<'PY'
import re, sys, datetime, collections
import xml.etree.ElementTree as ET
from xml.sax.saxutils import quoteattr
tmp, root, outpath, branch, head = sys.argv[1:6]

def rd(p): return open(p, encoding='utf-8').read()
def inner(s):
    m = re.search(r'<manifest[^>]*>(.*)</manifest>', s, re.S)
    return m.group(1).strip('\n')

text = rd(f'{tmp}/default.xml')
# 2. absolute github remote
text, n = re.subn(r'(<remote\s+name="github"\s+)fetch="\.\."', r'\1fetch="https://github.com/"', text)
assert n == 1, 'github remote not found / not relative'
# 3. drop the ssh-only remote
text, n = re.subn(r'[ \t]*<remote\s+name="private"[^>]*/>[ \t]*\n', '', text)
# 1. inline includes
for name in ('crdroid', 'lineage'):
    text, n = re.subn(r'<include\s+name="snippets/%s\.xml"\s*/>' % name,
                      lambda m, s=inner(rd(f'{tmp}/snippets/{name}.xml')): s, text)
    assert n == 1, f'include of snippets/{name}.xml not found'
assert '<include' not in text

base = ET.fromstring(text)
remotes = {r.get('name') for r in base.findall('remote')}
by_path = {}
for p in base.findall('project'):
    by_path[p.get('path', p.get('name'))] = p.get('name')

# doha block from the repo-root (LineageOS build) manifest
tsv = [l.rstrip('\n').split('|') for l in open(f'{root}/mirrors/MIRRORS.tsv') if l.strip() and not l.startswith('#')]
doha_names = [r[0] for r in tsv]
kit = ET.parse(f'{root}/default.xml').getroot()
kit_remotes = {r.get('name'): r for r in kit.findall('remote')}
kit_projects = {p.get('name'): p for p in kit.findall('project')}
missing = [n for n in doha_names if n not in kit_projects]
assert not missing, f'doha projects missing from root default.xml: {missing}'

def ser(el):
    return '<%s %s />' % (el.tag, ' '.join('%s=%s' % (k, quoteattr(v)) for k, v in el.attrib.items()))

need_remotes = []
for n in doha_names:
    rn = kit_projects[n].get('remote')
    if rn and rn not in remotes and rn not in need_remotes:
        need_remotes.append(rn)
lines = ['', '  <!-- ===== doha device-side projects (generated by crdroid-16/refresh-manifest.sh) =====',
         '       Copied verbatim from the repo-root default.xml: the exact pins of the working',
         '       LineageOS 23.2 build. scripts/restore-mirrors.sh repoints them at the local',
         '       mirror pool exactly as it does for the LineageOS target. -->']
for rn in need_remotes:
    lines.append('  ' + ser(kit_remotes[rn]))
removed = []
for n in doha_names:
    p = kit_projects[n]
    path = p.get('path', p.get('name'))
    if path in by_path and by_path[path] != n:
        removed.append((by_path[path], path))
for old, path in removed:
    lines.append(f'  <remove-project name={quoteattr(old)} />  <!-- same path as the doha project below: {path} -->')
for n in doha_names:
    lines.append('  ' + ser(kit_projects[n]))
block = '\n'.join(lines) + '\n'

header = ('<!-- crDroid on Android 16 (crDroid 12.x) + doha device projects.\n'
          f'     Generated {datetime.datetime.now(datetime.timezone.utc):%Y-%m-%d} by crdroid-16/refresh-manifest.sh from\n'
          f'     crdroidandroid/android branch {branch} @ {head}.\n'
          '     NOT SHA-pinned (crDroid moves daily); build.sh records each sync in\n'
          '     <src>/.repo/doha-crdroid16-pins.xml. Do not edit by hand - regenerate. -->\n')
text = text.replace('<manifest>', '<manifest>\n' + header, 1)
idx = text.rindex('</manifest>')
text = text[:idx].rstrip('\n') + '\n' + block + '</manifest>\n'
if not text.startswith('<?xml'):
    text = '<?xml version="1.0" encoding="UTF-8"?>\n' + text

# ---- self-check: process the manifest the way repo does ----------------------
root_el = ET.fromstring(text)
table = collections.OrderedDict()
for el in root_el:
    if el.tag == 'project':
        pth = el.get('path', el.get('name'))
        assert pth not in table, f'duplicate path {pth}: {table[pth]} vs {el.get("name")}'
        table[pth] = el.get('name')
    elif el.tag == 'remove-project':
        hit = [k for k, v in table.items() if v == el.get('name')]
        assert hit, f'remove-project of unknown project {el.get("name")}'
        for k in hit: del table[k]
defined = {r.get('name') for r in root_el.findall('remote')}
for el in root_el.findall('project'):
    rn = el.get('remote')
    assert rn is None or rn in defined, f'project {el.get("name")} uses undefined remote {rn}'
for r in root_el.findall('remote'):
    assert not r.get('fetch', '').startswith('..'), f'relative remote {r.get("name")}'
for n in doha_names:
    assert any(v == n for v in table.values()), f'doha project {n} missing from result'
open(outpath, 'w', encoding='utf-8').write(text)
print(f'wrote {outpath}: {len(table)} projects (27 doha), removed {len(removed)} colliding: {[o for o,_ in removed]}')
PY
echo "crDroid $BRANCH @ $head_sha"
