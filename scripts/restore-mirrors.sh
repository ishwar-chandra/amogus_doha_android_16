#!/usr/bin/env bash
# =============================================================================
# restore-mirrors.sh - turn the vendored tarballs into a LOCAL git mirror pool
# and repoint repo sync at it (file://), so the build no longer contacts
# Aldair402 / moto-common / AOSPA / ThankYouMario at all.
#
# Usage:  bash scripts/restore-mirrors.sh <source-tree>     e.g. ~/doha/src
#
# What it does:
#   1. untars mirrors/repos/<name>.tgz  ->  mirrors/git/<name>   (bare repos)
#   2. sets uploadpack.allowAnySHA1InWant on each (fetch-by-SHA works)
#   3. writes <source-tree>/.repo/local_manifests/doha-mirror.xml that
#      removes the 27 upstream project entries and re-adds them pointing at
#      the local mirror pool, with the SAME pinned SHAs
#   4. idempotent: re-running refreshes everything
#
# After this, `repo sync` (and build.sh) work even if every upstream repo
# is deleted. The 1,157 platform projects (LineageOS/AOSP) still come from
# the network - those are permanent, mirrored infrastructure.
# =============================================================================
set -uo pipefail
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
SRC="${1:-${DOHA_SRC:-$HOME/doha/src}}"
LIST="$HERE/mirrors/MIRRORS.tsv"
GITDIR="$HERE/mirrors/git"
LMP="$SRC/.repo/local_manifests"

[ -f "$LIST" ] || { echo "restore-mirrors: no $LIST - run scripts/vendor-mirrors.sh first"; exit 1; }
[ -d "$SRC/.repo" ] || { echo "restore-mirrors: $SRC is not a repo-initialized tree (no .repo)"; echo "run the sync/build first, or: cd $SRC && repo init -u <kit> -m default.xml"; exit 1; }

if ! mkdir -p "$GITDIR" "$LMP" 2>/dev/null || [ ! -w "$GITDIR" ]; then
  # e.g. the kit bind-mounted read-only into Docker: without this guard the
  # script "succeeded" with 0 mirrors and pointed repo sync at folders that
  # do not exist. build.sh treats a failure here as "sync from upstream".
  echo "restore-mirrors: cannot write $GITDIR (kit mounted read-only?) - mirrors NOT restored; sync falls back to upstream" >&2
  exit 1
fi
n=0
while IFS='|' read -r name path remote rev date url size; do
  case "$name" in \#*|"") continue ;; esac
  tgz="$HERE/mirrors/repos/$name.tgz"
  [ -s "$tgz" ] || { echo "  missing tarball for $name (skipped)"; continue; }
  rm -rf "$GITDIR/$name"
  mkdir -p "$GITDIR/$name"
  tar -xzf "$tgz" -C "$GITDIR/$name" --strip-components=1
  git -C "$GITDIR/$name" config uploadpack.allowAnySHA1InWant true
  # verify the pinned SHA survived the trip
  if [ "$(git -C "$GITDIR/$name" cat-file -t "$rev" 2>/dev/null)" = commit ]; then
    n=$((n+1))
  else
    echo "  BROKEN mirror: $name (pinned sha not present after restore!)"
  fi
done < "$LIST"
echo "restore-mirrors: $n usable mirrors in $GITDIR"

# ---- generate the local_manifest override -------------------------------------
XML="$LMP/doha-mirror.xml"
{
  echo '<?xml version="1.0" encoding="UTF-8"?>'
  echo "<!-- AUTO-GENERATED by restore-mirrors.sh $(date +%F) - do not edit."
  echo "     Repoints the 27 device-specific projects at the local mirror pool"
  echo "     so repo sync never contacts the community upstreams. -->"
  echo '<manifest>'
  echo "  <remote name=\"dohamirror\" fetch=\"file://$GITDIR\"/>"
  while IFS='|' read -r name path remote rev date url size; do
    case "$name" in \#*|"") continue ;; esac
    [ -s "$HERE/mirrors/repos/$name.tgz" ] || continue
    echo "  <remove-project name=\"$name\"/>"
  done < "$LIST"
  while IFS='|' read -r name path remote rev date url size; do
    case "$name" in \#*|"") continue ;; esac
    [ -s "$HERE/mirrors/repos/$name.tgz" ] || continue
    echo "  <project name=\"$name\" path=\"$path\" remote=\"dohamirror\" revision=\"$rev\" groups=\"local::doha\"/>"
  done < "$LIST"
  echo '</manifest>'
} > "$XML"
echo "restore-mirrors: wrote $XML"
echo "next: repo sync -c -j8   (device projects now come from the local mirror)"
